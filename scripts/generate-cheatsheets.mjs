import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const argumentsAfterScript = process.argv.slice(2);
const requested = argumentsAfterScript.filter(
  (arg) => !arg.startsWith("--"),
);
const checkOnly = argumentsAfterScript.includes("--check");
const languages = requested.length > 0 ? requested : ["golang", "python"];

for (const language of languages) {
  generate(language, checkOnly);
}

function generate(language, check) {
  const cheatsheetDirectory = path.join(
    root,
    "templates",
    language,
    "cheatsheets",
  );
  const manifestPath = path.join(cheatsheetDirectory, "manifest.json");
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const marker = language === "golang" ? "// ===" : "# ===";
  const requirementPattern =
    language === "golang"
      ? /^\/\/ Requires: import "([^"]+)"$/gm
      : /^# Requires: import ([A-Za-z0-9_.]+)$/gm;

  const sectionBodies = [];
  const imports = new Set();
  for (const relativeSection of manifest.sections) {
    const sectionPath = path.join(cheatsheetDirectory, relativeSection);
    const source = readFileSync(sectionPath, "utf8");
    const bodyStart = source.indexOf(marker);
    if (bodyStart < 0) {
      throw new Error(`${relativeSection} has no section banner`);
    }
    sectionBodies.push(source.slice(bodyStart).trim());
    for (const match of source.matchAll(requirementPattern)) {
      imports.add(match[1]);
    }
  }

  let output =
    language === "golang"
      ? renderGo(manifest, imports, sectionBodies)
      : renderPython(manifest, imports, sectionBodies);
  if (language === "golang") {
    output = execFileSync("gofmt", { input: output, encoding: "utf8" });
  }

  const outputPath = path.join(cheatsheetDirectory, manifest.output);
  if (check) {
    const existing = readFileSync(outputPath, "utf8");
    if (existing !== output) {
      throw new Error(
        `${path.relative(root, outputPath)} is stale; regenerate it`,
      );
    }
    console.log(`verified ${path.relative(root, outputPath)}`);
    return;
  }

  writeFileSync(outputPath, output);
  console.log(`generated ${path.relative(root, outputPath)}`);
}

function renderGo(manifest, imports, sectionBodies) {
  const intro = manifest.intro.map((line) => `// ${line}`).join("\n");
  const importBlock = [...imports]
    .sort()
    .map((name) => `\t"${name}"`)
    .join("\n");
  return `${intro}
//
// Code generated by scripts/generate-cheatsheets.mjs; DO NOT EDIT.
// Source: manifest-ordered topic files in this directory (excluding this file).
// Edit the numbered files, then run: npm run cheatsheets:generate
//
//go:build ignore

package main

import (
${importBlock}
)

${sectionBodies.join("\n\n")}
`;
}

function renderPython(manifest, imports, sectionBodies) {
  const intro = manifest.intro.join("\n");
  const importBlock = [...imports]
    .sort()
    .map((name) => `import ${name}`)
    .join("\n");
  return `"""${intro}

Code generated by scripts/generate-cheatsheets.mjs; DO NOT EDIT.
Source: manifest-ordered topic files in this directory (excluding this file).
Edit the numbered files, then run: npm run cheatsheets:generate
"""

from __future__ import annotations

# ruff: noqa: E402, F401, F811, F841
# pyright: reportUnusedImport=false, reportUnusedVariable=false

${importBlock}

${sectionBodies.join("\n\n")}
`;
}
